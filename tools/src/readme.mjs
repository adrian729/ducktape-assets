// `readme <set-repo-dir> [--manifest manifest.json]`: generates README.md, LICENSE.md and (historical sets) SOURCES.md.
// Deterministic and idempotent: same inputs, same bytes. Sorted by id; no timestamps.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';
import sharp from 'sharp';
import YAML from 'yaml';
import { exists, LICENSE_URLS } from './setfiles.mjs';

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const SCOPE = '@ranx729';

async function loadAssets(repoDir) {
  const dir = path.join(repoDir, 'assets');
  if (!(await exists(dir))) return [];
  const names = (await readdir(dir, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name).sort();
  const out = [];
  for (const name of names) {
    const file = path.join(dir, name, 'asset.yaml');
    if (!(await exists(file))) continue;
    const asset = YAML.parse(await readFile(file, 'utf8'));
    if (asset && typeof asset === 'object') out.push({ dir: path.join(dir, name), asset });
  }
  return out;
}

async function sizeOf(entry, manifest) {
  const m = manifest?.assets?.[entry.asset.id];
  if (m?.width && m?.height) return `${m.width} × ${m.height}`;
  try {
    const meta = await sharp(path.join(entry.dir, entry.asset.master), { limitInputPixels: false }).metadata();
    if (meta.width && meta.height) return `${meta.width} × ${meta.height}`;
  } catch { /* unreadable master: validate reports it */ }
  return '-';
}

function cdnExample(set, manifest, assets) {
  const pkg = `${SCOPE}/ducktape-assets-${set.id}`;
  const real = manifest?.version && manifest.version !== '0.0.0';
  if (real) {
    const cdn = manifest.cdn ?? `https://cdn.jsdelivr.net/npm/${pkg}@${manifest.version}/`;
    for (const id of Object.keys(manifest.assets ?? {}).sort()) {
      const files = manifest.assets[id]?.sources?.webp ?? [];
      if (files.length) {
        const f = files[Math.min(files.length - 1, Math.max(0, files.findIndex((x) => x.w >= 512)))];
        return { real: true, url: cdn + f.path, id, pkg, version: manifest.version };
      }
    }
    return { real: true, url: `${cdn}manifest.json`, id: assets[0]?.asset.id, pkg, version: manifest.version };
  }
  return { real: false, url: `https://cdn.jsdelivr.net/npm/${pkg}@<version>/webp/<asset-id>-<width>.webp`, id: assets[0]?.asset.id ?? '<asset-id>', pkg, version: '<version>' };
}

export function buildReadme(set, entries, sizes, manifest) {
  const L = [];
  const license = set.license?.artwork ?? 'unspecified';
  const draftCount = entries.filter((e) => e.asset.status === 'draft').length;
  L.push('<!-- Generated by `ducktape-assets-tools readme` from set.yaml, assets/*/asset.yaml and the last build. Edit those, not this file. -->');
  L.push(`# ${set.title}`, '', set.summary ?? '', '');
  L.push(`Part of [Ducktape Assets](https://github.com/adrian729/ducktape-assets). Set id \`${set.id}\`, ${set.kind}, ${entries.length} asset${entries.length === 1 ? '' : 's'}${manifest?.version ? `, version ${manifest.version}` : ''}.`, '');
  if (draftCount) L.push(`> ${draftCount} of ${entries.length} assets are still drafts awaiting review; nothing here is published until they are approved.`, '');
  L.push('## Licence and attribution', '');
  L.push(`Artwork: **${license}**${LICENSE_URLS[license] ? ` ([text](${LICENSE_URLS[license]}))` : ''}. ${set.license?.notes ?? ''}`.trim(), '');
  L.push(`Author: ${set.author}. Maintainer: ${set.maintainer ?? 'n/a'}. See [LICENSE.md](LICENSE.md)${set.kind === 'historical' ? ' and [SOURCES.md](SOURCES.md)' : ''}.`, '');
  const ex = cdnExample(set, manifest, entries);
  L.push('## Use one asset', '');
  if (ex.real) {
    L.push(`Pin the exact version (never \`@latest\`). For \`${set.id}/${ex.id}\`:`, '', '```html', `<img src="${ex.url}" alt="" loading="lazy">`, '```', '');
  } else {
    L.push('No version is published yet. Once it is, pin the exact version (never `@latest`); the URL scheme is:', '', '```', ex.url, '```', '');
  }
  L.push(`Package \`${ex.pkg}\`; every file, width and format is listed in its \`manifest.json\`. Masters live in git under \`assets/<id>/\` and in \`${ex.pkg}-masters\`; never put a master on a page.`, '');
  L.push('## Assets', '', '| id | title | type | size | group | status |', '| --- | --- | --- | --- | --- | --- |');
  for (const e of entries) {
    const a = e.asset;
    L.push(`| \`${esc(a.id)}\` | ${esc(a.title)} | ${esc(a.type)} | ${esc(sizes.get(a.id))} | ${esc(a.group ?? '')} | ${esc(a.status)} |`);
  }
  return L.join('\n') + '\n';
}

function rightsOf(a) {
  const p = a.provenance;
  return p?.image_rights ?? p?.rights_text ?? null;
}

export function buildLicense(set, entries) {
  const L = ['<!-- Generated by `ducktape-assets-tools readme`. -->', '# Licence', ''];
  const license = set.license?.artwork ?? 'unspecified';
  L.push('## Artwork', '', `Every asset in this repository is licensed **${license}** unless its own record says otherwise.`);
  if (LICENSE_URLS[license]) L.push('', `Licence text: ${LICENSE_URLS[license]}`);
  else L.push('', 'This is a custom identifier, not an SPDX licence; the conditions are in the notes below and in each asset\'s provenance.');
  if (set.license?.notes) L.push('', `Notes: ${set.license.notes}`);
  L.push('', '## Attribution', '');
  if (license === 'CC-BY-4.0') L.push(`Credit "${set.title}" by ${set.author} (${set.id}), licensed CC-BY-4.0, with a link to ${LICENSE_URLS['CC-BY-4.0']}.`);
  else if (set.kind === 'historical') L.push(`Artwork is extracted from objects held by the institutions listed in [SOURCES.md](SOURCES.md). Credit the holding institution and ${set.author} as the extraction author.`);
  else L.push(`Credit ${set.author}. See the notes above for further conditions.`);
  const overrides = entries.filter((e) => e.asset.license);
  if (overrides.length) {
    L.push('', '## Per-asset licences', '', '| asset | licence |', '| --- | --- |');
    for (const e of overrides) L.push(`| \`${esc(e.asset.id)}\` | ${esc(e.asset.license)} |`);
  }
  const rights = entries.filter((e) => rightsOf(e.asset) && rightsOf(e.asset) !== license);
  if (rights.length) {
    L.push('', '## Recorded rights statements', '', '| asset | statement |', '| --- | --- |');
    for (const e of rights) L.push(`| \`${esc(e.asset.id)}\` | ${esc(rightsOf(e.asset))} |`);
  }
  L.push('', '## Code', '', 'Code in this repository (workflows, scripts) is MIT licensed.');
  return L.join('\n') + '\n';
}

export function buildSources(set, entries) {
  const L = ['<!-- Generated by `ducktape-assets-tools readme` from the provenance records of each asset. -->', `# Sources: ${set.title}`, ''];
  if (set.origin) L.push(`Set origin: ${[set.origin.institution, set.origin.object_title, set.origin.object_identifier].filter(Boolean).join(', ')}.`, '');
  const groups = new Map();
  for (const e of entries) {
    const p = e.asset.provenance;
    if (!p) continue;
    const key = [p.institution, p.object_identifier].filter(Boolean).join(' | ') || '(unnamed object)';
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(e.asset);
  }
  for (const key of [...groups.keys()].sort()) {
    const list = groups.get(key);
    const p0 = list[0].provenance;
    L.push(`## ${key.replace(' | ', ', ')}`, '');
    const facts = [
      ['Title', p0.object_title], ['Date', p0.date], ['Artist', p0.artist], ['Record', p0.record_url], ['Image', p0.image_url],
      ['Rights', p0.image_rights ?? p0.rights_text], ['Rights page', p0.rights_url],
    ].filter(([, v]) => v);
    for (const [k, v] of facts) L.push(`- ${k}: ${v}`);
    L.push('', '| asset | method | source sha256 |', '| --- | --- | --- |');
    for (const a of list) L.push(`| \`${esc(a.id)}\` | ${esc(a.provenance.method)} | ${esc(a.provenance.source_sha256 ?? '')} |`);
    L.push('');
  }
  return L.join('\n').replace(/\n+$/, '\n');
}

export async function generateReadme(repoDir, { manifestPath } = {}) {
  const set = YAML.parse(await readFile(path.join(repoDir, 'set.yaml'), 'utf8'));
  const manifest = manifestPath ? JSON.parse(await readFile(manifestPath, 'utf8')) : null;
  const entries = await loadAssets(repoDir);
  const sizes = new Map();
  for (const e of entries) sizes.set(e.asset.id, await sizeOf(e, manifest));
  const files = { 'README.md': buildReadme(set, entries, sizes, manifest), 'LICENSE.md': buildLicense(set, entries) };
  if (set.kind === 'historical') files['SOURCES.md'] = buildSources(set, entries);
  for (const [name, text] of Object.entries(files)) await writeFile(path.join(repoDir, name), text);
  return Object.keys(files);
}

export async function runReadme(argv) {
  const { values, positionals } = parseArgs({ args: argv, allowPositionals: true, options: { manifest: { type: 'string' } } });
  const dir = positionals[0] ?? '.';
  const written = await generateReadme(dir, { manifestPath: values.manifest });
  console.log(`wrote ${written.join(', ')} in ${dir}`);
}
